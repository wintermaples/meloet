#[test]
fn latency_and_audio_json_shape() {
    both_ways(
        LatencyView {
            reported_ms: Some(8.0),
            measured_ms: Some(12.5),
            manual_ms: None,
            used: LatencySource::Measured,
            used_ms: Some(12.5),
        },
        json!({"reportedMs": 8.0, "measuredMs": 12.5, "manualMs": null, "used": "measured",
               "usedMs": 12.5}),
    );
    assert_eq!(
        json!([
            LatencySource::Reported,
            LatencySource::Measured,
            LatencySource::Manual
        ]),
        json!(["reported", "measured", "manual"])
    );
    for (measure, json) in [
        (LatencyMeasure::Idle, json!({"state": "idle"})),
        (
            LatencyMeasure::Measuring {
                done: 3,
                of: LATENCY_CLICKS,
                mean_ms: Some(12.5),
            },
            json!({"state": "measuring", "done": 3, "of": 5, "meanMs": 12.5}),
        ),
        (
            LatencyMeasure::Done { measured_ms: 12.25 },
            json!({"state": "done", "measuredMs": 12.25}),
        ),
        (
            LatencyMeasure::Failed {
                reason: LatencyFailure::TooQuiet,
            },
            json!({"state": "failed", "reason": "tooQuiet"}),
        ),
        (
            LatencyMeasure::Failed {
                reason: LatencyFailure::Unsteady,
            },
            json!({"state": "failed", "reason": "unsteady"}),
        ),
        (
            LatencyMeasure::Failed {
                reason: LatencyFailure::NoInput,
            },
            json!({"state": "failed", "reason": "noInput"}),
        ),
    ] {
        both_ways(LatencyDialogView { measure }, json!({"measure": json}));
    }
}

