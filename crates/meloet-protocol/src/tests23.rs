use std::path::PathBuf;

use serde_json::{Value, json};

use super::*;

fn to_json<T: serde::Serialize>(v: &T) -> Value {
    serde_json::to_value(v).unwrap()
}

/// `v` writes `json`, and `json` reads back as `v`.
fn both_ways<T>(v: T, json: Value)
where
    T: serde::Serialize + serde::de::DeserializeOwned + PartialEq + std::fmt::Debug,
{
    assert_eq!(to_json(&v), json);
    assert_eq!(serde_json::from_value::<T>(json).unwrap(), v);
}

fn vocal_track() -> TrackRef {
    TrackRef {
        number: 6,
        name: "歌".to_owned(),
    }
}

/// Writes `ui/src/bridge/generated/vocal.ts`: the lists the screen shows in this order.
#[test]
fn export_vocal_lists() {
    let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../ui/src/bridge/generated");
    std::fs::create_dir_all(&dir).unwrap();
    std::fs::write(
        dir.join("vocal.ts"),
        format!(
            "// Written by `cargo test -p meloet-protocol`. Do not edit this file manually.\n\
             import type {{ RecordFormat }} from \"./RecordFormat\";\n\
             import type {{ VocalInput }} from \"./VocalInput\";\n\n\
             /** The rows of the list under 「入口 1 ・ モノ ▾」, top first. */\n\
             export const VOCAL_INPUTS: readonly VocalInput[] = {};\n\n\
             /** 「録る形」, with the bits each writes. */\n\
             export const RECORD_FORMATS: readonly {{ readonly format: RecordFormat; \
             readonly bits: number }}[] = {};\n\n\
             /** How many clicks 「遅れを測る」 plays. */\n\
             export const LATENCY_CLICKS = {LATENCY_CLICKS};\n",
            json!(VocalInput::ALL),
            json!(
                RecordFormat::ALL
                    .iter()
                    .map(|f| json!({"format": f, "bits": f.bits()}))
                    .collect::<Vec<_>>()
            ),
        ),
    )
    .unwrap();
}

#[test]
fn vocal_inputs_are_the_models_in_the_same_order() {
    assert_eq!(
        json!(VocalInput::ALL),
        json!(["mono1", "mono2", "stereo12"])
    );
    assert_eq!(VocalInput::ALL.len(), meloet_model::VocalInput::ALL.len());
    assert_eq!(VocalInput::default(), VocalInput::Mono1);
    assert_eq!(
        json!(RecordFormat::ALL),
        json!(["bits16", "bits24", "bits32"])
    );
    assert_eq!(RecordFormat::default().bits(), 24);
    assert_eq!(LATENCY_CLICKS, 5);
}

