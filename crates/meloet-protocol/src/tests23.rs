#[test]
fn selected_sound_and_step_what_json_shape() {
    both_ways(
        SelectedParams::Sound(SelectedSound {
            track: 1,
            sound: SoundName::Sf2 {
                name: "Clean Guitar".to_owned(),
                file: "FluidR3_GM.sf2".to_owned(),
            },
        }),
        json!({"kind": "sound", "track": 1,
               "sound": {"kind": "sf2", "name": "Clean Guitar", "file": "FluidR3_GM.sf2"}}),
    );
    let pad = TrackRef {
        number: 4,
        name: "パッド".to_owned(),
    };
    for (what, json) in [
        (
            StepWhat::Note { key: 60 },
            json!({"kind": "note", "key": 60}),
        ),
        (
            StepWhat::Quantized {
                division: 16,
                triplet: false,
                count: 12,
            },
            json!({"kind": "quantized", "division": 16, "triplet": false, "count": 12}),
        ),
        (
            StepWhat::Velocity {
                count: 3,
                from: Some(96),
                to: Some(110),
            },
            json!({"kind": "velocity", "count": 3, "from": 96, "to": 110}),
        ),
        (
            StepWhat::Velocity {
                count: 3,
                from: None,
                to: None,
            },
            json!({"kind": "velocity", "count": 3, "from": null, "to": null}),
        ),
        (
            StepWhat::ControlPoints {
                control: Some(ControlKind::Cc { number: 64 }),
                count: 4,
            },
            json!({"kind": "controlPoints", "control": {"kind": "cc", "number": 64},
                   "count": 4}),
        ),
        (
            StepWhat::Color {
                track: pad.clone(),
                color: 3,
            },
            json!({"kind": "color", "track": {"number": 4, "name": "パッド"}, "color": 3}),
        ),
        (
            StepWhat::SoundReplaced {
                track: pad.clone(),
                from: SoundName::Builtin {
                    instrument: InstrumentKind::GrandPiano,
                },
                to: SoundName::Plugin {
                    name: "Surge XT".to_owned(),
                },
            },
            json!({"kind": "soundReplaced", "track": {"number": 4, "name": "パッド"},
                   "from": {"kind": "builtin", "instrument": "grandPiano"},
                   "to": {"kind": "plugin", "name": "Surge XT"}}),
        ),
        (
            StepWhat::VocalInput {
                track: vocal_track(),
                from: VocalInput::Mono1,
                to: VocalInput::Mono2,
            },
            json!({"kind": "vocalInput", "track": {"number": 6, "name": "歌"},
                   "from": "mono1", "to": "mono2"}),
        ),
    ] {
        both_ways(what, json);
    }
    assert_eq!(
        to_json(&StepName::SetVocalInput),
        json!({"kind": "setVocalInput"})
    );
}
