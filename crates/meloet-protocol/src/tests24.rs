fn sample_peaks() -> Peaks {
    Peaks {
        audio: 31,
        level: 2,
        channels: 2,
        growing: true,
        first: 5,
        total: 9,
        // Three peaks of two channels: smallest, largest.
        values: vec![
            -32_768, 32_767, -1, 1, -12_000, 9_000, -300, 20_000, 0, 0, -5, 7,
        ],
    }
}

#[test]
fn peaks_layout_matches_the_table() {
    let p = sample_peaks();
    let bytes = p.encode();
    assert_eq!(bytes.len(), PEAKS_HEADER_LEN + 3 * 2 * 4);
    assert_eq!(&bytes[..8], &[PEAKS_KIND, PEAKS_VERSION, 2, 2, 1, 0, 0, 0]);
    assert_eq!(&bytes[8..12], &31u32.to_le_bytes());
    assert_eq!(&bytes[12..16], &5u32.to_le_bytes());
    assert_eq!(&bytes[16..20], &3u32.to_le_bytes());
    assert_eq!(&bytes[20..24], &9u32.to_le_bytes());
    assert_eq!(&bytes[24..28], &[0x00, 0x80, 0xff, 0x7f]);
    assert_eq!(p.count(), 3);
}

#[test]
fn peaks_round_trip_and_reject_bad_input() {
    let p = sample_peaks();
    let bytes = p.encode();
    assert_eq!(Peaks::decode(&bytes), Ok(p));
    let empty = Peaks {
        audio: 1,
        channels: 1,
        ..Peaks::default()
    };
    assert_eq!(Peaks::decode(&empty.encode()), Ok(empty));

    assert_eq!(
        Peaks::decode(&bytes[..10]),
        Err(PeaksError::TooShort { len: 10 })
    );
    let with = |at: usize, value: u8| {
        let mut b = bytes.clone();
        b[at] = value;
        Peaks::decode(&b)
    };
    assert_eq!(with(0, 2), Err(PeaksError::WrongKind(2)));
    assert_eq!(with(1, 9), Err(PeaksError::WrongVersion(9)));
    assert_eq!(with(2, 5), Err(PeaksError::WrongLevel(5)));
    assert_eq!(with(3, 0), Err(PeaksError::WrongChannels(0)));
    assert_eq!(with(3, 3), Err(PeaksError::WrongChannels(3)));
    assert_eq!(
        Peaks::decode(&bytes[..bytes.len() - 1]),
        Err(PeaksError::WrongLength {
            len: bytes.len() - 1,
            expected: bytes.len()
        })
    );
}

