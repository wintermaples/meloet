#[test]
fn audio_clip_json_shape() {
    both_ways(
        sample_audio_clip(),
        json!({"audio": 31, "file": "歌 テイク 1.wav", "sampleRate": 44_100, "bits": 24,
               "channels": 1, "resampled": true, "firstFrame": 12_000, "frames": 441_000,
               "fadeIn": 240, "fadeOut": 0, "gainDb": -3.0, "state": "ready",
               "stretch": {"follow": true, "sourceBpm": 120.0, "ratio": 1.0, "semitones": 0,
                           "cents": 0, "keepFormant": true},
               "sourceTempo": {"tempoBpm": 120.0, "headRamp": false, "tempoPoints": []}}),
    );
    assert_eq!(
        json!([
            AudioClipState::Ready,
            AudioClipState::Loading,
            AudioClipState::Missing
        ]),
        json!(["ready", "loading", "missing"])
    );
    let clip = ClipView {
        id: 9,
        name: "歌 テイク 1".to_owned(),
        start: 46_080,
        end: 61_440,
        take: 1,
        takes: 1,
        take_id: 40,
        take_offset: -1920,
        note_count: 0,
        audio: Some(AudioClipView {
            bits: None,
            stretch: StretchView {
                follow: false,
                source_bpm: None,
                ratio: None,
                semitones: 2,
                cents: -30,
                keep_formant: false,
            },
            source_tempo: None,
            ..sample_audio_clip()
        }),
    };
    let v = to_json(&clip);
    assert_eq!(v["audio"]["bits"], Value::Null);
    assert_eq!(
        v["audio"]["stretch"],
        json!({"follow": false, "sourceBpm": null, "ratio": null, "semitones": 2,
               "cents": -30, "keepFormant": false})
    );
    assert_eq!(v["audio"]["sourceTempo"], Value::Null);
    assert_eq!(serde_json::from_value::<ClipView>(v).unwrap(), clip);
}

#[test]
fn command_24_json_shape() {
    for (command, json) in [
        (Command::SplitClips, json!({"type": "splitClips"})),
        (
            Command::SetClipField {
                clip: 9,
                field: ClipField::GainDb,
                value: -3.0,
            },
            json!({"type": "setClipField", "clip": 9, "field": "gainDb", "value": -3.0}),
        ),
        (
            Command::SetClipField {
                clip: 9,
                field: ClipField::FadeOut,
                value: 480.0,
            },
            json!({"type": "setClipField", "clip": 9, "field": "fadeOut", "value": 480.0}),
        ),
        (
            Command::SetTallTrack { track: Some(6) },
            json!({"type": "setTallTrack", "track": 6}),
        ),
        (
            Command::SetTallTrack { track: None },
            json!({"type": "setTallTrack", "track": null}),
        ),
        (
            Command::ImportAudio { track: None },
            json!({"type": "importAudio", "track": null}),
        ),
        (
            Command::DropAudio {
                drop: 3,
                track: Some(6),
                tick: 30_720,
                mode: DropMode::InRow,
            },
            json!({"type": "dropAudio", "drop": 3, "track": 6, "tick": 30_720, "mode": "inRow"}),
        ),
        (
            Command::FindAudio { audio: 31 },
            json!({"type": "findAudio", "audio": 31}),
        ),
        (
            Command::RemoveMissing {
                missing: MissingRef::Audio { audio: 31 },
            },
            json!({"type": "removeMissing", "missing": {"kind": "audio", "audio": 31}}),
        ),
    ] {
        both_ways(command, json);
    }
    assert_eq!(
        json!([
            ClipField::Start,
            ClipField::Length,
            ClipField::GainDb,
            ClipField::FadeIn,
            ClipField::FadeOut
        ]),
        json!(["start", "length", "gainDb", "fadeIn", "fadeOut"])
    );
    assert_eq!(
        json!([DropMode::Separate, DropMode::InRow]),
        json!(["separate", "inRow"])
    );
    assert_eq!(DropMode::default(), DropMode::Separate);
}

