fn to_json<T: serde::Serialize>(v: &T) -> Value {
    serde_json::to_value(v).unwrap()
}

/// `v` writes `json`, and `json` reads back as `v`.
fn both_ways<T>(v: T, json: Value)
where
    T: serde::Serialize + serde::de::DeserializeOwned + PartialEq + std::fmt::Debug,
{
    assert_eq!(to_json(&v), json);
    assert_eq!(serde_json::from_value::<T>(json).unwrap(), v);
}

fn ui_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../ui")
}

/// Writes `ui/src/bridge/generated/audio.ts`: the numbers of the peaks and of the clip's
/// volume, and the endings that read as audio.
#[test]
fn export_audio_lists() {
    let dir = ui_dir().join("src/bridge/generated");
    std::fs::create_dir_all(&dir).unwrap();
    std::fs::write(
        dir.join("audio.ts"),
        format!(
            "// Written by `cargo test -p meloet-protocol`. Do not edit this file manually.\n\n\
             /** The range of a vocal clip's volume in dB. */\n\
             export const CLIP_GAIN_MIN_DB = {CLIP_GAIN_MIN_DB};\n\
             export const CLIP_GAIN_MAX_DB = {CLIP_GAIN_MAX_DB};\n\n\
             /** 「音の高さ」: −max..=max semitones and cents. */\n\
             export const CLIP_SEMITONES_MAX = {CLIP_SEMITONES_MAX};\n\
             export const CLIP_CENTS_MAX = {CLIP_CENTS_MAX};\n\
             /** The range of a typed 「この音のテンポ」, in steps of 0.01. */\n\
             export const SOURCE_BPM_MIN = {SOURCE_BPM_MIN};\n\
             export const SOURCE_BPM_MAX = {SOURCE_BPM_MAX};\n\n\
             /** The endings of the files that read as audio, as the status line lists them. */\n\
             export const AUDIO_EXTENSIONS: readonly string[] = {};\n\n\
             /** The peaks binary (docs/architecture.md 22-17). */\n\
             export const PEAKS_KIND = {PEAKS_KIND};\n\
             export const PEAKS_VERSION = {PEAKS_VERSION};\n\
             export const PEAKS_HEADER_LEN = {PEAKS_HEADER_LEN};\n\
             /** Frames of the file to a peak, for each level. */\n\
             export const PEAK_LEVELS: readonly number[] = {};\n\
             /** The most peaks one `peaks` reply carries. */\n\
             export const PEAKS_MAX_COUNT = {PEAKS_MAX_COUNT};\n",
            json!(AUDIO_EXTENSIONS),
            json!(PEAK_LEVELS),
        ),
    )
    .unwrap();
}

#[test]
fn the_numbers_are_the_models() {
    assert_eq!(f64::from(CLIP_GAIN_MIN_DB), meloet_model::ClipGain::MIN_DB);
    assert_eq!(f64::from(CLIP_GAIN_MAX_DB), meloet_model::ClipGain::MAX_DB);
    assert_eq!(PEAK_LEVELS[0], 256);
    assert!(PEAK_LEVELS.windows(2).all(|w| w[1] == 4 * w[0]));
    assert_eq!(
        json!(AUDIO_EXTENSIONS),
        json!(["wav", "mp3", "flac", "ogg"])
    );
}

