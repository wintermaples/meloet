//! The shapes protocol 34 added (round 12 after the features, the owner's answers of
//! 2026-11-24): mute sets on the screen (B-97-3, B-97-5), their step names (B-97-2), and the
//! step name of a batch of the AI link (B-97-1).

use serde_json::{Value, json};

use super::*;

fn to_json<T: serde::Serialize>(v: &T) -> Value {
    serde_json::to_value(v).unwrap()
}

fn both_ways<T>(v: T, json: Value)
where
    T: serde::Serialize + serde::de::DeserializeOwned + PartialEq + std::fmt::Debug,
{
    assert_eq!(to_json(&v), json);
    assert_eq!(serde_json::from_value::<T>(json).unwrap(), v);
}

#[test]
fn the_commands_of_mute_sets() {
    both_ways(
        Command::SaveMuteSet {
            name: "サビ".into(),
            overwrite: false,
        },
        json!({"type": "saveMuteSet", "name": "サビ", "overwrite": false}),
    );
    both_ways(
        Command::RecallMuteSet {
            name: "サビ".into(),
        },
        json!({"type": "recallMuteSet", "name": "サビ"}),
    );
    both_ways(
        Command::DeleteMuteSet {
            name: "サビ".into(),
        },
        json!({"type": "deleteMuteSet", "name": "サビ"}),
    );
    both_ways(
        Command::RenameMuteSet {
            name: "サビ".into(),
            to: "大サビ".into(),
        },
        json!({"type": "renameMuteSet", "name": "サビ", "to": "大サビ"}),
    );
}

#[test]
fn the_song_lists_its_sets() {
    both_ways(
        MuteSetView {
            name: "ドラムだけ".into(),
            as_now: false,
        },
        json!({"name": "ドラムだけ", "asNow": false}),
    );
    let state = to_json(&tests::sample_state());
    assert_eq!(
        state["song"]["muteSets"],
        json!([{"name": "サビ", "asNow": true}])
    );
}

#[test]
fn the_new_step_names() {
    let names = [
        (StepName::SaveMuteSet, "saveMuteSet"),
        (StepName::RecallMuteSet, "recallMuteSet"),
        (StepName::DeleteMuteSet, "deleteMuteSet"),
        (StepName::RenameMuteSet, "renameMuteSet"),
    ];
    for (name, kind) in names {
        assert!(StepName::every_kind().contains(&name), "{kind}");
        both_ways(name, json!({"kind": kind}));
    }
    both_ways(
        StepName::Batch { count: 15 },
        json!({"kind": "batch", "count": 15}),
    );
    assert!(
        (StepName::every_kind().iter()).any(|n| matches!(n, StepName::Batch { .. })),
        "batch"
    );
}

